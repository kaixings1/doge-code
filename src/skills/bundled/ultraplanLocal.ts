import { registerBundledSkill } from '../bundledSkills.js'

/**
 * 深度规划技能 —— 对标官方 Opus 云端 Ultraplan 的本地替代。
 *
 * 官方版把任务发到 CCR 云端、最多跑 30 分钟、在浏览器里人工审批；
 * 这里用同一条「先侦察现状 → 多方案对比 → 分步实施 → 验证方式」的骨架，
 * 在本地会话里跑，产物写入计划目录，供 /ultraplan-local 与 /plan 复用。
 */
const PROMPT = `# 深度规划（Ultraplan）

你正在执行一次深度规划。目标是在**不修改业务代码**的前提下，产出一份可以直接照着做的实施计划。

## 阶段

### 1. 边界确认
用不超过 5 行写清：要达成什么、明确不做什么、验收标准是什么。
如果用户没给验收标准，先给出你认为合理的标准，并标记为「待确认」。

### 2. 现状侦察
- 找出相关入口、关键文件、数据流，用 \`file:line\` 标注
- 找出既有的可复用实现（先搜再做，避免重复造轮子）
- 记录已知的坑（注释、TODO、既有测试覆盖范围）

### 3. 方案对比
给出 2-3 个候选方案，每个方案包含：
- 一段话描述
- 改动面（哪些文件、大致行数规模）
- 优点 / 风险
最后明确选定一个，并说明为什么不选其它。

### 4. 分步实施
拆成可独立验证的最小步骤。每步写：
- 要改什么（文件路径）
- 为什么这样改
- 怎么验证（测试命令、断言、或手动确认方式）

### 5. 风险与回滚
列出最容易出错的 2-3 个点，以及每一点出错时的信号与回滚动作。

### 6. 待确认问题
把需要用户拍板的点列成清单。如果没有，写「无」。

## 产出

1. 把完整计划写入计划目录（\`~/.doge/plans/\`，文件名用简短英文 slug）
2. 在对话中给出不超过 20 行的摘要
3. 不要直接开始实施 —— 等用户确认后再动手
`

export function registerUltraplanLocalSkill(): void {
  registerBundledSkill({
    name: 'ultraplan-local',
    description: '深度规划（本地版）— 侦察现状、对比方案、拆分可验证步骤，产物写入计划目录。',
    whenToUse:
      '当任务复杂、涉及多个模块、或用户希望在动手前先看到完整方案时；也是 /ultraplan（云端版）不可用时的替代。',
    userInvocable: true,
    getPromptForCommand() {
      return [{ type: 'text', text: PROMPT }]
    },
  })
}
