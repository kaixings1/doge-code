// 去重：过滤掉标记为"重复项"的记录，并按字合并读音
const dynMap = new Map();
for (const [ch, reads, tip] of DY) {
  if (typeof tip === 'string' && tip.includes('重复项')) continue;
  if (typeof reads === 'string' && reads === '内') continue;
  const prev = dynMap.get(ch);
  if (prev) {
    for (const r of reads) {
      if (!prev.reads.some((x) => x[0] === r[0])) prev.reads.push(r);
    }
  } else {
    dynMap.set(ch, { ch, reads: [...reads], tip });
  }
}
const dynList = [...dynMap.values()];

